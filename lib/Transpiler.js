/* jshint esversion: 6 */

var Buffer = require('./Buffer');
var Grammar = require('./Grammar');

// transpiler
class Transpiler extends Grammar
{
  constructor(data)
  {
    // AMOS data buffer
    super(new Buffer(new Uint8Array(data)));

    // Simple IR
    this._ops = [];
    this._labels = {};
    this._fixups = [];

    // hooks for Grammar action side-effects
    this._emit = (op) => {
      this._ops.push(op);
    };
    this._defineLabel = (name) => {
      this._labels[name] = this._ops.length;
    };

    // parse program (side-effects populate ops/labels)
    this.run();
  }

  // Temporary scaffold: emit a minimal driver-based module around parsed program
  toModule()
  {
    // resolve labels to indices
    const labelIndex = (name) => {
      if (name in this._labels) return this._labels[name];
      // record unresolved for diagnostics
      this._fixups.push(name);
      return 0;
    };

    // predeclare assigned variables
    const declared = new Set();
    for (const op of this._ops) {
      if (op.kind === 'assign') declared.add(op.target);
    }

    const caseLines = [];
    let lastKey = null;
    for (let i = 0; i < this._ops.length; i++) {
      const op = this._ops[i];
      let body = '';
      switch (op.kind) {
        case 'print':
          body = `console.log(${op.expr}); return {};`;
          break;
        case 'branch_false':
          body = `if (!(${op.cond})) { return { goto: ${labelIndex(op.label)} }; } return {};`;
          break;
        case 'end':
          body = `return { halt: true };`;
          break;
        case 'assign':
          body = `${op.target} = (${op.expr}); return {};`;
          break;
        case 'goto':
          body = `return { goto: ${labelIndex(op.label)} };`;
          break;
        case 'nop':
          body = `return {};`;
          break;
        case 'gosub':
          body = `return { call: ${labelIndex(op.label)} };`;
          break;
        case 'return':
          body = `return { ret: true };`;
          break;
        default:
          body = `return {};`;
      }
      // de-duplicate consecutive identical ops (temporary guard against grammar duplicates)
      const key = JSON.stringify({ k: op.kind, t: op.target, e: op.expr, l: op.label, b: body });
      if (key === lastKey) {
        // emit a no-op to preserve IP sequencing but avoid duplicated effects
        caseLines.push(`    cases[${i}] = function(state){ return {}; };`);
      } else {
        lastKey = key;
        caseLines.push(`    cases[${i}] = function(state){ ${body} };`);
      }
    }

    const prelude = [
      "/* Auto-generated by amoscript (driver module) */",
      "(function(factory){",
      "  if (typeof module === 'object' && module.exports) module.exports = factory(require('./amos/driver'));",
      "  else window.AMOS_MODULE = factory(window.AMOS_DRIVER);",
      "})(function(driver){",
      "  const createProgram = (driver && (driver.createProgram || driver.AMOS_DRIVER && driver.AMOS_DRIVER.createProgram)) || driver.createProgram;",
      "  return function create(opts){",
      "    const cases = [];",
      declared.size ? `    let ${Array.from(declared).join(', ')};` : ''
    ];
    const postlude = [
      "    return createProgram(cases, opts || {});",
      "  };",
      "});"
    ];
    return prelude.concat(caseLines).concat(postlude).join('\n');
  }
}

module.exports = Transpiler;
